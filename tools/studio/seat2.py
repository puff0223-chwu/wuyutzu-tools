import bed, shot
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(); c = b.new_context(viewport={'width': 1366, 'height': 860}); bed.setup(c)
    t = c.new_page(); t.on('pageerror', lambda e: print('TERR', e)); t.on('dialog', lambda d: d.accept())
    t.goto(bed.ORIGIN + '/classroom/seating/'); t.wait_for_timeout(2500)
    t.locator('[data-act="tab"]', has_text='教室地圖').click(); t.wait_for_timeout(800); shot.save(t, 'seat_map_raw')
    t.locator('[data-act="tab"]', has_text='換座位').click(); t.wait_for_timeout(800)
    t.click('[data-act="newRound"]'); t.wait_for_timeout(400); t.click('#nrOk'); t.wait_for_timeout(1500)
    shot.save(t, 'seat_round_raw')
    btns = t.evaluate("Array.from(document.querySelectorAll('button')).map(b=>b.textContent.trim()).filter(Boolean).join(' | ')"); print(btns)
    with c.expect_page() as pi: t.locator('button', has_text='開啟投影舞台').first.click()
    st = pi.value; st.on('pageerror', lambda e: print('SERR', e)); st.wait_for_timeout(2500)
    shot.save(st, 'seat_stage0')
    st.click('#stDraw'); st.wait_for_timeout(5500); shot.save(st, 'seat_stage_mid')
    if st.locator('#stSkip:visible').count(): st.click('#stSkip')
    st.wait_for_timeout(3000)
    if st.locator('button', has_text='好').count(): st.locator('button', has_text='好').first.click()
    st.wait_for_timeout(600); shot.save(st, 'seat_stage_done')
    t.bring_to_front(); t.reload(); t.wait_for_timeout(2500)
    t.locator('[data-act="tab"]', has_text='座位表').click(); t.wait_for_timeout(1500)
    shot.save(t, 'seat_sheet_raw'); t.screenshot(path='out/raw_seat_sheet_full.png', full_page=True)
    print(t.evaluate("Array.from(document.querySelectorAll('[class*=sheet],[id*=sheet]')).map(e=>e.tagName+'.'+e.className+'#'+e.id).slice(0,10).join('\\n')"))
    b.close()
